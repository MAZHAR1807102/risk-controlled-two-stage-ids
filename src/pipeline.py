"""Clean, reproducible training + evaluation pipeline for the two-stage IDS.

Replaces Paper_final_verion.ipynb. Differences from the notebook, all deliberate:
  * full CICIoT2023 splits (no 10% sampling), fixed seeds
  * no Gaussian-noise / FGSM augmentation (it produced physically impossible flows)
  * Stage 2 early-stops on VALIDATION (the notebook used the test set)
  * Gatekeeper uses group-balanced weights (fixes the Recon/Spoofing/BruteForce misses)
  * tau is chosen on validation against a worst-attack-group miss-rate target
  * the test split is scored exactly once, at the end
  * every table is written from code; the C++ scaler header is generated, not pasted

Usage:
  .venv/bin/python src/pipeline.py --run runs/seed42 --seed 42
"""
import argparse
import json
import os
import platform
import time

import numpy as np
import pandas as pd
import xgboost as xgb
import sklearn
from sklearn.metrics import (classification_report, confusion_matrix,
                             roc_auc_score, average_precision_score)

from datasets import get_dataset
from train_gatekeeper import (group_miss, pick_tau,
                              summarize, weights)

# Set in main() from the chosen dataset.
DS = None
CLASSES = []
BENIGN = 0
TAU_TARGETS = [0.01, 0.02, 0.05]

STAGE1_PARAMS = {"objective": "binary:logistic", "max_depth": 6, "eta": 0.3,
                 "tree_method": "hist", "eval_metric": "logloss"}
STAGE1_ROUNDS = 100

# Same hyperparameters as the notebook's Stage 2, so differences in results come
# from the protocol fixes rather than from retuning.
STAGE2_PARAMS = {"objective": "multi:softprob",  # num_class set in main()
                 "max_depth": 10, "eta": 0.05, "subsample": 0.8,
                 "colsample_bytree": 0.8, "lambda": 3.0, "min_child_weight": 10,
                 "tree_method": "hist", "eval_metric": "mlogloss"}
STAGE2_MAX_ROUNDS = 1000
STAGE2_EARLY_STOP = 50


def log(msg):
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


FRAC = 1.0  # set by --frac; < 1 only for smoke tests


def load(split):
    X, g, raw, feats = DS.load(split, FRAC)
    log(f"{DS.name} {split}: {len(g):,} rows, {X.shape[1]} features")
    return X, g, raw, feats


def fit_scaler(X):
    # float64 accumulation, as sklearn's StandardScaler; zero-variance -> scale 1.
    mean = X.astype(np.float64).mean(0)
    std = X.astype(np.float64).std(0)
    std[std == 0] = 1.0
    return mean, std


def scale(X, mean, std):
    return (X - mean.astype(np.float32)) / std.astype(np.float32)


def write_cpp_header(path, mean, std, tau, feature_names):
    fmt = lambda a: ", ".join(repr(float(v)) for v in a)
    with open(path, "w") as f:
        f.write("// Generated by pipeline.py -- do not edit by hand.\n")
        f.write("// Feature order: " + ", ".join(feature_names) + "\n")
        f.write("#pragma once\n\n")
        f.write(f"const float SCALER_MEANS[{len(mean)}] = {{ {fmt(mean)} }};\n\n")
        f.write(f"const float SCALER_SCALES[{len(std)}] = {{ {fmt(std)} }};\n\n")
        f.write(f"const float GATEKEEPER_TAU = {tau!r}f;\n")


def class_weights(y, scheme="balanced"):
    """'balanced' = sklearn weights (the notebook's choice); 'sqrt' = square root of
    those, normalised to mean sample weight 1. Full balancing over-predicts the rare
    classes on the full split (BruteForce/Web precision ~0.25)."""
    counts = np.bincount(y, minlength=len(CLASSES))
    w = len(y) / (len(CLASSES) * np.maximum(counts, 1))
    if scheme == "sqrt":
        w = np.sqrt(w)
        w = w / (w[y].mean())
    return w


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="runs/seed42")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--tau-target", type=float, default=0.02,
                    help="max per-attack-group miss rate on validation for the deployed tau")
    ap.add_argument("--nthread", type=int, default=-1)
    ap.add_argument("--stage2-weighting", choices=["balanced", "sqrt"], default="sqrt")
    ap.add_argument("--frac", type=float, default=1.0, help="row fraction; smoke tests only")
    ap.add_argument("--dataset", default="ciciot2023", choices=["ciciot2023", "ciciomt2024"])
    ap.add_argument("--select-frac", type=float, default=0.0,
                    help="if > 0: early-stop Stage 2 on this stratified random share of the TRAIN split "
                         "(Stage 2 is fitted on the rest), so the validation split is never seen by "
                         "Stage 2 and stays pure calibration data for the whole-system certificate")
    args = ap.parse_args()
    global FRAC, DS, CLASSES, BENIGN
    FRAC = args.frac
    DS = get_dataset(args.dataset)
    CLASSES = DS.classes
    BENIGN = CLASSES.index("Benign")
    STAGE2_PARAMS["num_class"] = len(CLASSES)
    os.makedirs(args.run, exist_ok=True)
    t_start = time.time()

    # ---- Data -------------------------------------------------------------------
    Xtr, gtr, _, feat = load("train")
    Xva, gva, _, _ = load("validation")
    mean, std = fit_scaler(Xtr)  # fit on train only
    Xtr, Xva = scale(Xtr, mean, std), scale(Xva, mean, std)
    ytr = np.array([CLASSES.index(c) for c in gtr])
    yva = np.array([CLASSES.index(c) for c in gva])
    common = {"seed": args.seed, "nthread": args.nthread}

    # ---- Stage 1: Gatekeeper ------------------------------------------------------
    log("Training Stage 1 (group-balanced Gatekeeper) ...")
    t = time.time()
    d1 = xgb.QuantileDMatrix(Xtr, (ytr != BENIGN).astype(np.float32),
                             weight=weights(gtr, "group_balanced"))
    stage1 = xgb.train({**STAGE1_PARAMS, **common}, d1, STAGE1_ROUNDS)
    stage1_train_s = time.time() - t
    del d1
    stage1.save_model(f"{args.run}/layer1_gatekeeper.json")
    stage1.save_model(f"{args.run}/layer1_gatekeeper.ubj")  # binary: ~3.5x less RAM to load on the edge

    # ---- tau selection on validation ---------------------------------------------
    p_va = stage1.predict(xgb.DMatrix(Xva))
    taus = {f"{t:.0%}": pick_tau(p_va, gva, t) for t in TAU_TARGETS}
    tau = pick_tau(p_va, gva, args.tau_target)
    log(f"tau by target (validation): {taus}; deployed tau = {tau:.3f}")

    # ---- Stage 2: Deep inspection -------------------------------------------------
    if args.select_frac > 0:
        # Selection split carved from train, stratified by class; validation is not touched.
        rng = np.random.default_rng(args.seed)
        sel = np.zeros(len(ytr), bool)
        for c in np.unique(ytr):
            i = np.flatnonzero(ytr == c)
            sel[rng.choice(i, int(round(args.select_frac * len(i))), replace=False)] = True
        X2, y2, Xes, yes = Xtr[~sel], ytr[~sel], Xtr[sel], ytr[sel]
        log(f"Training Stage 2 (early stopping on {sel.sum()} held-out TRAIN rows; validation unseen) ...")
    else:
        X2, y2, Xes, yes = Xtr, ytr, Xva, yva
        log("Training Stage 2 (balanced multiclass, early stopping on validation) ...")
    cw = class_weights(y2, args.stage2_weighting)
    t = time.time()
    d2 = xgb.QuantileDMatrix(X2, y2, weight=cw[y2].astype(np.float32))
    # Early-stopping rows weighted with the same class weights, so early stopping tracks the
    # balanced objective instead of DDoS-dominated log-loss.
    d2va = xgb.DMatrix(Xes, yes, weight=cw[yes].astype(np.float32))
    stage2 = xgb.train({**STAGE2_PARAMS, **common}, d2, STAGE2_MAX_ROUNDS,
                       evals=[(d2va, "val")], early_stopping_rounds=STAGE2_EARLY_STOP,
                       verbose_eval=50)
    stage2_train_s = time.time() - t
    del d2, d2va, Xtr, X2, Xes
    # Keep only rounds up to the best one; the C++ predictor uses every saved tree.
    best = stage2.best_iteration
    stage2 = stage2[: best + 1]
    stage2.save_model(f"{args.run}/layer2_multiclass.json")
    stage2.save_model(f"{args.run}/layer2_multiclass.ubj")
    log(f"Stage 2 best iteration {best} ({stage2.num_boosted_rounds()} rounds kept)")

    write_cpp_header(f"{args.run}/ids_params.h", mean, std, tau, feat)

    # ---- Test: scored once ------------------------------------------------------------
    log("Scoring test split (single pass) ...")
    Xte, gte, rawte, _ = load("test")
    Xte = scale(Xte, mean, std)
    yte = np.array([CLASSES.index(c) for c in gte])
    dte = xgb.DMatrix(Xte)
    p_att = stage1.predict(dte)
    p_cls = stage2.predict(dte)
    pred2 = p_cls.argmax(1)
    flag = p_att >= tau
    pred_e2e = np.where(flag, pred2, BENIGN)

    ybin = (yte != BENIGN).astype(int)
    stage1_rows = [{"selection": f"val worst-group miss<={k}", **summarize(p_att, gte, v, DS.stealthy)}
                   for k, v in taus.items()]
    pd.DataFrame(stage1_rows).to_csv(f"{args.run}/stage1_operating_points.csv", index=False)

    miss = pd.DataFrame({"group": gte, "label": rawte, "missed": ~flag})
    (miss[miss.group != "Benign"].groupby(["group", "label"])["missed"]
     .agg(n="size", missed="sum", miss_rate="mean")
     .to_csv(f"{args.run}/stage1_miss_by_attack.csv"))

    reports = {}
    for name, pred in (("single_stage", pred2), ("two_stage", pred_e2e)):
        rep = classification_report(yte, pred, labels=range(len(CLASSES)),
                                    target_names=CLASSES, digits=4,
                                    output_dict=True, zero_division=0)
        pd.DataFrame(rep).T.to_csv(f"{args.run}/{name}_report.csv")
        pd.DataFrame(confusion_matrix(yte, pred, labels=range(len(CLASSES))),
                     index=CLASSES, columns=CLASSES).to_csv(f"{args.run}/{name}_confusion.csv")
        reports[name] = {"accuracy": rep["accuracy"],
                         "macro_f1": rep["macro avg"]["f1-score"],
                         "macro_recall": rep["macro avg"]["recall"],
                         "weighted_f1": rep["weighted avg"]["f1-score"],
                         "per_class_f1": {c: rep[c]["f1-score"] for c in CLASSES},
                         "per_class_recall": {c: rep[c]["recall"] for c in CLASSES}}

    np.savez_compressed(f"{args.run}/test_scores.npz", p_att=p_att.astype(np.float32),
                        p_cls=p_cls.astype(np.float16), y=yte)

    metrics = {
        "run": args.run, "seed": args.seed, "dataset": DS.name, "classes": CLASSES,
        "versions": {"xgboost": xgb.__version__, "sklearn": sklearn.__version__,
                     "numpy": np.__version__, "python": platform.python_version(),
                     "machine": platform.platform()},
        "data": {"train_rows": int(len(gtr)), "val_rows": int(len(gva)),
                 "test_rows": int(len(gte)),
                 "test_class_counts": {c: int((gte == c).sum()) for c in CLASSES}},
        "stage1": {"params": STAGE1_PARAMS, "rounds": STAGE1_ROUNDS,
                   "weighting": "group_balanced", "train_seconds": stage1_train_s,
                   "tau_target": args.tau_target, "tau": tau, "tau_by_target": taus,
                   "test_roc_auc": float(roc_auc_score(ybin, p_att)),
                   "test_pr_auc_benign": float(average_precision_score(1 - ybin, 1 - p_att)),
                   "test_at_tau": summarize(p_att, gte, tau, DS.stealthy)},
        "stage2": {"params": STAGE2_PARAMS, "best_iteration": int(best),
                   "weighting": args.stage2_weighting,
                   "class_weights": dict(zip(CLASSES, map(float, cw))),
                   "train_seconds": stage2_train_s,
                   "early_stopping_data": (f"{args.select_frac:.0%} of train" if args.select_frac > 0
                                           else "validation")},
        "test": reports,
        "wall_seconds": time.time() - t_start,
    }
    json.dump(metrics, open(f"{args.run}/metrics.json", "w"), indent=2)

    s = metrics["stage1"]["test_at_tau"]
    log("DONE")
    print(f"tau={tau:.3f}  benign_bypass={s['benign_bypass']:.4f}  "
          f"worst_group_miss={s['worst_group_miss']:.4f}  overall_fnr={s['overall_fnr']:.5f}")
    print(pd.DataFrame({k: {"accuracy": v["accuracy"], "macro_f1": v["macro_f1"],
                            "macro_recall": v["macro_recall"]} for k, v in reports.items()})
          .to_string(float_format=lambda v: f"{v:.4f}"))
    print(pd.DataFrame({k: v["per_class_f1"] for k, v in reports.items()})
          .to_string(float_format=lambda v: f"{v:.4f}"))


if __name__ == "__main__":
    main()
